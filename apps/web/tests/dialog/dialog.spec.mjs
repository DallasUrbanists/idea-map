test('top-right X button is named, has a touch target and restores focus on close', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 480 })
  await page.goto('/tests/dialog/')
  const trigger = page.getByRole('button', { name: 'Open dialog' })
  await trigger.click()
  const dialog = page.getByRole('dialog')
  const close = dialog.getByRole('button', { name: 'Close', exact: true })
  await expect(close).toHaveText('')
  await expect(close.locator('svg')).toHaveAttribute('aria-hidden', 'true')
  await dialog.getByRole('heading').evaluate(el => { el.textContent = 'A long dialog title that must wrap beside the close button' })
  const bounds = await dialog.boundingBox()
  const buttonBounds = await close.boundingBox()
  const titleBounds = await dialog.getByRole('heading').boundingBox()
  expect(buttonBounds.width).toBeGreaterThanOrEqual(44)
  expect(buttonBounds.height).toBeGreaterThanOrEqual(44)
  expect(buttonBounds.x).toBeGreaterThan(bounds.x + bounds.width / 2)
  expect(buttonBounds.y - bounds.y).toBeLessThanOrEqual(32)
  expect(buttonBounds.x + buttonBounds.width).toBeLessThanOrEqual(bounds.x + bounds.width)
  expect(titleBounds.x + titleBounds.width).toBeLessThanOrEqual(buttonBounds.x)
  await close.click()
  await expect(dialog).toHaveCount(0)
  await expect(trigger).toBeFocused()
})
