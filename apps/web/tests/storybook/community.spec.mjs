import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

const story = '/iframe.html?id=components-community-patterns--owner&viewMode=story'

test('keyboard and repeated recovery preserve comment text', async ({ page }) => {
  await page.goto(story)
  const comment = page.getByLabel('Your comment')
  await comment.fill('A synthetic suggestion')
  await page.getByRole('button', { name: 'Toggle offline' }).click()
  await expect(page.getByRole('button', { name: 'Send comment' })).toBeDisabled()
  await expect(comment).toHaveValue('A synthetic suggestion')
  await page.getByRole('button', { name: 'Toggle offline' }).click()
  await page.getByRole('button', { name: 'Simulate pending' }).click()
  await expect(page.getByRole('button', { name: 'Sending…' })).toHaveAttribute('aria-busy', 'true')
  await page.getByRole('button', { name: 'Sending…' }).focus()
  await page.keyboard.press('Enter')
  await expect(comment).toHaveValue('A synthetic suggestion')
  await page.getByRole('button', { name: 'Simulate error' }).click()
  await expect(comment).toHaveAttribute('aria-invalid', 'true')
  const description = await comment.getAttribute('aria-describedby')
  await expect(page.locator(`[id="${description}"]`)).toContainText('could not be sent')
  await page.getByRole('button', { name: 'Send comment' }).focus()
  await page.keyboard.press('Enter')
  await expect(comment).toHaveValue('A synthetic suggestion')
  await page.getByRole('button', { name: 'Send comment' }).click()
  await expect(page.getByText('A synthetic suggestion')).toBeVisible()
  await expect(comment).toHaveValue('')
  await comment.fill('Another synthetic suggestion')
  await page.getByRole('button', { name: 'Send comment' }).click()
  await expect(page.getByText('Another synthetic suggestion')).toBeVisible()
  const like = page.getByRole('button', { name: 'Like', exact: true })
  await like.focus()
  await page.keyboard.press('Space')
  await expect(like).toHaveAttribute('aria-pressed', 'true')
  await expect(like).toBeFocused()
  await page.keyboard.press('Space')
  await expect(like).toHaveAttribute('aria-pressed', 'false')
})

test('roles, responsive layout, reduced motion and automated accessibility', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 600 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto(story)
  await expect(page.locator('body')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const results = await new AxeBuilder({ page }).analyze()
  expect(results.violations).toEqual([])
  await page.goto('/iframe.html?id=components-community-patterns--guest&viewMode=story')
  await expect(page.getByRole('button', { name: 'Like', exact: true })).toBeDisabled()
  await expect(page.getByText('Sign in to join the discussion.')).toBeVisible()
  await page.goto('/iframe.html?id=components-community-patterns--moderator&viewMode=story')
  await expect(page.getByRole('button', { name: 'Review comment by Avery' })).toBeVisible()
})
